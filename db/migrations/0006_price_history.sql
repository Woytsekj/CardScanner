-- Provider-scoped product price history and application price alerts.
--
-- Schema only. No production SQLite data is imported by this migration.
-- Historical product prices belong to the provider catalog; alert delivery
-- records belong to application activity.
--
-- Legacy numeric IDs must be explicitly preserved during import. After an
-- import, identity sequences must be advanced beyond the maximum imported ID.

CREATE TABLE catalog.product_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_product_id TEXT NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL,
    source_updated TEXT NOT NULL,
    normal_price DOUBLE PRECISION,
    foil_price DOUBLE PRECISION,
    CONSTRAINT product_price_history_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT product_price_history_product_id_nonempty
        CHECK (btrim(external_product_id) <> ''),
    CONSTRAINT product_price_history_source_update_uq
        UNIQUE (
            game_id,
            provider_id,
            external_product_id,
            source_updated
        )
);

CREATE INDEX catalog_product_price_history_lookup_idx
    ON catalog.product_price_history (
        game_id,
        provider_id,
        external_product_id,
        captured_at DESC
    );

COMMENT ON TABLE catalog.product_price_history IS
    'Historical provider product prices. Normal and foil prices are independently nullable; legacy numeric IDs are preserved.';

COMMENT ON COLUMN catalog.product_price_history.source_updated IS
    'Provider source-update timestamp used for snapshot deduplication.';

COMMENT ON COLUMN catalog.product_price_history.captured_at IS
    'Timestamp when CardScanner captured the provider price snapshot.';

CREATE TABLE app.price_alert_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_product_id TEXT NOT NULL,
    finish TEXT NOT NULL,
    alerted_at TIMESTAMPTZ NOT NULL,
    old_price DOUBLE PRECISION NOT NULL,
    new_price DOUBLE PRECISION NOT NULL,
    percent_change DOUBLE PRECISION NOT NULL,
    owned_quantity INTEGER NOT NULL DEFAULT 0,
    owned_value_gain DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    CONSTRAINT price_alert_log_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT price_alert_log_product_id_nonempty
        CHECK (btrim(external_product_id) <> ''),
    CONSTRAINT price_alert_log_finish_nonempty
        CHECK (btrim(finish) <> '')
);

CREATE INDEX app_price_alert_log_lookup_idx
    ON app.price_alert_log (
        game_id,
        provider_id,
        external_product_id,
        finish,
        alerted_at DESC
    );

COMMENT ON TABLE app.price_alert_log IS
    'Application records of successfully delivered product price alerts, scoped by game, provider, product, and finish.';

COMMENT ON COLUMN app.price_alert_log.owned_value_gain IS
    'Estimated value gain across the owned quantity at the time the alert was delivered.';
