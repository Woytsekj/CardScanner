-- Provider- and game-scoped tag catalog for artwork and canonical-card tags.
--
-- This migration is schema-only. It does not import data from production
-- SQLite. Scryfall's source tag IDs and Oracle IDs remain provider-scoped
-- external values; internal BIGINT IDs are used for relational integrity.
--
-- Importers must map source illustration IDs to catalog.illustrations rows
-- (including unresolved IDs with no known printing face) before inserting
-- art_tag_assignments. Oracle assignments intentionally retain the provider's
-- external Oracle ID and do not require a canonical card row to exist.

CREATE TABLE catalog.tags (
    tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_tag_id TEXT NOT NULL,
    tag_type TEXT NOT NULL,
    slug TEXT NOT NULL,
    label TEXT NOT NULL,
    description TEXT,
    parent_ids JSONB NOT NULL DEFAULT '[]'::JSONB,
    child_ids JSONB NOT NULL DEFAULT '[]'::JSONB,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT tags_game_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id) ON DELETE RESTRICT,
    CONSTRAINT tags_external_id_nonempty CHECK (btrim(external_tag_id) <> ''),
    CONSTRAINT tags_type_nonempty CHECK (btrim(tag_type) <> ''),
    CONSTRAINT tags_slug_nonempty CHECK (btrim(slug) <> ''),
    CONSTRAINT tags_label_nonempty CHECK (btrim(label) <> ''),
    CONSTRAINT tags_parent_ids_array CHECK (jsonb_typeof(parent_ids) = 'array'),
    CONSTRAINT tags_child_ids_array CHECK (jsonb_typeof(child_ids) = 'array'),
    CONSTRAINT tags_id_game_provider_uq UNIQUE (tag_id, game_id, provider_id),
    CONSTRAINT tags_id_game_provider_type_uq UNIQUE (tag_id, game_id, provider_id, tag_type),
    CONSTRAINT tags_provider_external_uq UNIQUE (game_id, provider_id, external_tag_id)
);

CREATE INDEX catalog_tags_type_slug_idx
    ON catalog.tags (game_id, provider_id, tag_type, lower(btrim(slug)));

CREATE INDEX catalog_tags_type_label_idx
    ON catalog.tags (game_id, provider_id, tag_type, lower(btrim(label)));

CREATE TABLE catalog.tag_aliases (
    tag_id BIGINT NOT NULL,
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    alias TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT tag_aliases_pk PRIMARY KEY (tag_id, alias),
    CONSTRAINT tag_aliases_tag_scope_fk
        FOREIGN KEY (tag_id, game_id, provider_id, tag_type)
        REFERENCES catalog.tags(tag_id, game_id, provider_id, tag_type) ON DELETE CASCADE,
    CONSTRAINT tag_aliases_nonempty CHECK (btrim(alias) <> '')
);

-- SQLite's former NOCASE uniqueness is represented explicitly and consistently.
CREATE UNIQUE INDEX catalog_tag_aliases_tag_normalized_uq
    ON catalog.tag_aliases (tag_id, lower(btrim(alias)));

CREATE INDEX catalog_tag_aliases_lookup_idx
    ON catalog.tag_aliases (game_id, provider_id, lower(btrim(alias)));

CREATE TABLE catalog.tag_closure (
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    tag_type TEXT NOT NULL,
    ancestor_tag_id BIGINT NOT NULL,
    descendant_tag_id BIGINT NOT NULL,
    depth INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT tag_closure_pk PRIMARY KEY (ancestor_tag_id, descendant_tag_id),
    CONSTRAINT tag_closure_ancestor_fk
        FOREIGN KEY (ancestor_tag_id, game_id, provider_id, tag_type)
        REFERENCES catalog.tags(tag_id, game_id, provider_id, tag_type) ON DELETE CASCADE,
    CONSTRAINT tag_closure_descendant_fk
        FOREIGN KEY (descendant_tag_id, game_id, provider_id, tag_type)
        REFERENCES catalog.tags(tag_id, game_id, provider_id, tag_type) ON DELETE CASCADE,
    CONSTRAINT tag_closure_depth_nonnegative CHECK (depth >= 0),
    CONSTRAINT tag_closure_not_self CHECK (ancestor_tag_id <> descendant_tag_id)
);

CREATE INDEX catalog_tag_closure_descendant_idx
    ON catalog.tag_closure (game_id, provider_id, descendant_tag_id);

CREATE TABLE catalog.art_tag_assignments (
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    tag_type TEXT NOT NULL DEFAULT 'art' CHECK (tag_type = 'art'),
    tag_id BIGINT NOT NULL,
    illustration_id BIGINT NOT NULL,
    weight TEXT,
    annotation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT art_tag_assignments_pk PRIMARY KEY (tag_id, illustration_id),
    CONSTRAINT art_tag_assignments_tag_scope_fk
        FOREIGN KEY (tag_id, game_id, provider_id, tag_type)
        REFERENCES catalog.tags(tag_id, game_id, provider_id, tag_type) ON DELETE CASCADE,
    CONSTRAINT art_tag_assignments_illustration_game_fk
        FOREIGN KEY (illustration_id, game_id)
        REFERENCES catalog.illustrations(illustration_id, game_id) ON DELETE CASCADE
);

CREATE INDEX catalog_art_tag_assignments_illustration_idx
    ON catalog.art_tag_assignments (game_id, provider_id, illustration_id);

CREATE INDEX catalog_art_tag_assignments_tag_idx
    ON catalog.art_tag_assignments (game_id, provider_id, tag_id);

CREATE TABLE catalog.oracle_tag_assignments (
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    tag_type TEXT NOT NULL DEFAULT 'oracle' CHECK (tag_type = 'oracle'),
    tag_id BIGINT NOT NULL,
    external_oracle_id TEXT NOT NULL,
    card_id BIGINT,
    weight TEXT,
    annotation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT oracle_tag_assignments_pk PRIMARY KEY (tag_id, external_oracle_id),
    CONSTRAINT oracle_tag_assignments_tag_scope_fk
        FOREIGN KEY (tag_id, game_id, provider_id)
        REFERENCES catalog.tags(tag_id, game_id, provider_id) ON DELETE CASCADE,
    CONSTRAINT oracle_tag_assignments_card_game_fk
        FOREIGN KEY (card_id, game_id)
        REFERENCES catalog.cards(card_id, game_id) ON DELETE SET NULL (card_id),
    CONSTRAINT oracle_tag_assignments_oracle_id_nonempty
        CHECK (btrim(external_oracle_id) <> '')
);

CREATE INDEX catalog_oracle_tag_assignments_oracle_idx
    ON catalog.oracle_tag_assignments (game_id, provider_id, external_oracle_id);

CREATE INDEX catalog_oracle_tag_assignments_card_idx
    ON catalog.oracle_tag_assignments (game_id, card_id)
    WHERE card_id IS NOT NULL;

COMMENT ON TABLE catalog.tags IS
    'Provider-scoped tags. Source tag identifiers and parent/child source IDs are retained separately from internal IDs.';

COMMENT ON TABLE catalog.tag_aliases IS
    'Case-insensitive aliases for provider-scoped tags; aliases may overlap across different tags.';

COMMENT ON TABLE catalog.tag_closure IS
    'Provider- and game-scoped transitive tag hierarchy. Depth is retained from the source closure calculation.';

COMMENT ON TABLE catalog.art_tag_assignments IS
    'Artwork tags attach to illustration identities, not printing faces. Illustrations need not have a currently known face.';

COMMENT ON TABLE catalog.oracle_tag_assignments IS
    'Oracle/card tags preserve the provider external Oracle ID even when no canonical catalog.cards row is currently resolvable.';

COMMENT ON COLUMN catalog.art_tag_assignments.weight IS
    'Original provider weight retained as TEXT to avoid lossy normalization during import.';

COMMENT ON COLUMN catalog.oracle_tag_assignments.weight IS
    'Original provider weight retained as TEXT to avoid lossy normalization during import.';
