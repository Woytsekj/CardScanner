-- Provider-scoped printing metadata and application lookup data.
--
-- Schema only. Production SQLite data is not imported by this migration.
-- Provider identifiers remain valid even when no normalized catalog printing
-- or canonical card has been resolved.

CREATE TABLE catalog.provider_printing_metadata (
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_printing_id TEXT NOT NULL,
    printing_id BIGINT,
    name TEXT,
    type_line TEXT,
    colors JSONB,
    colors_text TEXT,
    color_identity JSONB,
    mana_value DOUBLE PRECISION,
    mana_cost TEXT,
    oracle_text TEXT,
    external_oracle_id TEXT,
    legalities JSONB,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT provider_printing_metadata_pk
        PRIMARY KEY (game_id, provider_id, external_printing_id),
    CONSTRAINT provider_printing_metadata_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT provider_printing_metadata_printing_fk
        FOREIGN KEY (printing_id, game_id)
        REFERENCES catalog.printings(printing_id, game_id)
        ON DELETE SET NULL (printing_id),
    CONSTRAINT provider_printing_metadata_external_id_nonempty
        CHECK (btrim(external_printing_id) <> ''),
    CONSTRAINT provider_printing_metadata_colors_array
        CHECK (colors IS NULL OR jsonb_typeof(colors) = 'array'),
    CONSTRAINT provider_printing_metadata_identity_array
        CHECK (color_identity IS NULL OR jsonb_typeof(color_identity) = 'array'),
    CONSTRAINT provider_printing_metadata_legalities_object
        CHECK (legalities IS NULL OR jsonb_typeof(legalities) = 'object')
);

CREATE INDEX catalog_provider_printing_metadata_printing_idx
    ON catalog.provider_printing_metadata (game_id, printing_id)
    WHERE printing_id IS NOT NULL;

CREATE INDEX catalog_provider_printing_metadata_oracle_idx
    ON catalog.provider_printing_metadata (game_id, provider_id, external_oracle_id)
    WHERE external_oracle_id IS NOT NULL;

CREATE INDEX catalog_provider_printing_metadata_type_idx
    ON catalog.provider_printing_metadata (game_id, provider_id, lower(btrim(type_line)))
    WHERE type_line IS NOT NULL;

CREATE INDEX catalog_provider_printing_metadata_colors_idx
    ON catalog.provider_printing_metadata (game_id, provider_id, lower(btrim(colors_text)))
    WHERE colors_text IS NOT NULL;

-- Application-managed aliases retain their original numeric IDs. The
-- external printing ID is retained even when catalog resolution is absent.
CREATE TABLE app.card_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_printing_id TEXT NOT NULL,
    printing_id BIGINT,
    alias TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT card_aliases_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT card_aliases_printing_fk
        FOREIGN KEY (printing_id, game_id)
        REFERENCES catalog.printings(printing_id, game_id)
        ON DELETE SET NULL (printing_id),
    CONSTRAINT card_aliases_external_id_nonempty
        CHECK (btrim(external_printing_id) <> ''),
    CONSTRAINT card_aliases_alias_nonempty
        CHECK (btrim(alias) <> '')
);

-- SQLite's UNIQUE(scryfall_id, alias) with NOCASE collation.
CREATE UNIQUE INDEX app_card_aliases_printing_alias_uq
    ON app.card_aliases
       (game_id, provider_id, external_printing_id, lower(alias));

CREATE INDEX app_card_aliases_alias_idx
    ON app.card_aliases (game_id, provider_id, lower(alias));

CREATE INDEX app_card_aliases_printing_idx
    ON app.card_aliases (game_id, provider_id, external_printing_id);

-- A source printing can map to one product per target provider. Product IDs
-- may be NULL; this preserves unresolved mappings from the legacy database.
CREATE TABLE catalog.printing_product_mappings (
    game_id TEXT NOT NULL,
    source_provider_id TEXT NOT NULL,
    source_external_printing_id TEXT NOT NULL,
    target_provider_id TEXT NOT NULL,
    printing_id BIGINT,
    target_external_product_id TEXT,
    finishes JSONB NOT NULL DEFAULT '[]'::JSONB,
    card_name TEXT,
    set_code TEXT,
    collector_number TEXT,
    resolved_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT printing_product_mappings_pk
        PRIMARY KEY (
            game_id,
            source_provider_id,
            source_external_printing_id,
            target_provider_id
        ),
    CONSTRAINT printing_product_mappings_source_provider_fk
        FOREIGN KEY (game_id, source_provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT printing_product_mappings_target_provider_fk
        FOREIGN KEY (game_id, target_provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT printing_product_mappings_printing_fk
        FOREIGN KEY (printing_id, game_id)
        REFERENCES catalog.printings(printing_id, game_id)
        ON DELETE SET NULL (printing_id),
    CONSTRAINT printing_product_mappings_source_id_nonempty
        CHECK (btrim(source_external_printing_id) <> ''),
    CONSTRAINT printing_product_mappings_target_id_nonempty
        CHECK (
            target_external_product_id IS NULL
            OR btrim(target_external_product_id) <> ''
        ),
    CONSTRAINT printing_product_mappings_finishes_array
        CHECK (jsonb_typeof(finishes) = 'array')
);

CREATE INDEX catalog_printing_product_mappings_target_idx
    ON catalog.printing_product_mappings
       (game_id, target_provider_id, target_external_product_id)
    WHERE target_external_product_id IS NOT NULL;

CREATE INDEX catalog_printing_product_mappings_printing_idx
    ON catalog.printing_product_mappings (game_id, printing_id)
    WHERE printing_id IS NOT NULL;

-- Cached provider rulings remain keyed by their original external printing ID.
-- The JSON array is retained as a whole, including empty cached responses.
CREATE TABLE catalog.printing_rulings_cache (
    game_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    external_printing_id TEXT NOT NULL,
    printing_id BIGINT,
    rulings JSONB NOT NULL DEFAULT '[]'::JSONB,
    fetched_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT printing_rulings_cache_pk
        PRIMARY KEY (game_id, provider_id, external_printing_id),
    CONSTRAINT printing_rulings_cache_provider_fk
        FOREIGN KEY (game_id, provider_id)
        REFERENCES catalog.game_providers(game_id, provider_id)
        ON DELETE RESTRICT,
    CONSTRAINT printing_rulings_cache_printing_fk
        FOREIGN KEY (printing_id, game_id)
        REFERENCES catalog.printings(printing_id, game_id)
        ON DELETE SET NULL (printing_id),
    CONSTRAINT printing_rulings_cache_external_id_nonempty
        CHECK (btrim(external_printing_id) <> ''),
    CONSTRAINT printing_rulings_cache_rulings_array
        CHECK (jsonb_typeof(rulings) = 'array')
);

CREATE INDEX catalog_printing_rulings_cache_printing_idx
    ON catalog.printing_rulings_cache (game_id, printing_id)
    WHERE printing_id IS NOT NULL;

COMMENT ON TABLE catalog.provider_printing_metadata IS
    'Provider-sourced printing metadata. External IDs and payloads survive without normalized printing resolution.';

COMMENT ON TABLE app.card_aliases IS
    'Application-managed alternate printing names. Original numeric IDs and external provider printing IDs are retained.';

COMMENT ON COLUMN app.card_aliases.created_at IS
    'Legacy SQLite CURRENT_TIMESTAMP values are timezone-naive UTC and must be interpreted as UTC during import.';

COMMENT ON TABLE catalog.printing_product_mappings IS
    'Maps source-provider printing IDs to target-provider product IDs; unresolved target product IDs are allowed.';

COMMENT ON COLUMN catalog.printing_product_mappings.finishes IS
    'Provider-sourced finish list retained as JSONB to preserve its full array content and ordering.';

COMMENT ON TABLE catalog.printing_rulings_cache IS
    'Provider rulings cache keyed by external printing ID; empty cached arrays are valid.';
